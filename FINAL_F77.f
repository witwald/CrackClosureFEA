      SUBROUTINE SYMBAN(MAXN,N,M,MSUM,A,NRHS,B,IFAC,P,IERR,ALP,Z,W,D,NC)
C
C     SOLVE MATRIX EQUATION AX=B WHERE A IS SYMMETRIC POSITIVE DEFINITE
C     AND B IS A MATRIX OF CONSTANT VECTORS.
C     SYMMETRY AND BAND WIDTH OF MATRIX A IS ACCOUNTED FOR BY STORING A(I)
C     IN LOWER TRIANGULAR MATRIX (INCLUDING DIAGONAL) BY ROWS
C
C     MAXN - MAXIMUM DIMENSION OF MATRIX A
C
C     N - NUMBER OF ROWS OF MATRIX A
C
C     M(I) - BAND WIDTHS (LARGEST NUMBER OF NON-ZERO COLUMNS TO THE LEFT
C            AND INCLUDING THE DIAGONAL OF ROW I IN MATRIX A
C            M(I) MUST BE GREATER THAN OR EQUAL TO 2 WITH M(1)=1
C
C     MSUM(I) - AN ARRAY COMPUTED IN SYMBAN
C
C     NRHS - NUMBER OF RIGHT-HAND SIDES OF COLUMN VECTOR B
C
C     IFAC - INPUT INTEGER SPECIFYING WHETHER OR NOT A CHOLESKY
C            DECOMPOSITION OF MATRIX A IS TO BE COMPUTED
C            WHERE A = L*D*L**T
C
C          = 0   CHOLESKY DECOMPOSITION IS COMPUTED. IFAC SET TO 1.
C
C          = 1   THE CHOLESKY DECOMPOSED FORM OF MATRIX A IS INPUT.
C                SOLUTION IS RETURNED IN B.
C
C          = 2   THE CHOLESKY DECOMPOSITION OF MATRIX A IS MODIFIED.
C                MODIFICATION IS OF THE FORM A = A + ALP*Z*Z**T.
C                NC IS THE FIRST NONZERO ROW IN COLUMN VECTOR Z.
C                IFAC IS SET TO 1 AND Z SET TO 0 UPON RETURN.
C                SOLUTION IS RETURNED IN B.
C
C          = 3   ONLY THE CHOLESKY DECOMPOSITION OF MATRIX A IS MODIFIED.
C                IFAC IS SET TO 1 AND Z SET TO 0 UPON RETURN.
C
C*** F77: THE CDC 6000 SERIES USED 60-BIT SINGLE PRECISION (ABOUT 14
C***      DIGITS).  32-BIT REAL IS NOT ADEQUATE FOR THIS PROGRAM (THE
C***      RIGID-SPRING STIFFNESS SK2 = 1.0E7*CE IS ADDED TO AND LATER
C***      REMOVED FROM THE FACTORED MATRIX), SO DOUBLE PRECISION IS USED.
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      DIMENSION A(MAXN),B(N,NRHS),P(N),W(N),D(N),Z(N),M(N),MSUM(N)
      NM1 = N-1
      IF(NM1.GT.1) GO TO 20
      I=1
      IF (A(I) .LE. 0.0) GO TO 999
      P(I) = 1.0/A(I)
      DO 10 J=1,NRHS
      B(I,J) = B(I,J)*P(I)
   10 CONTINUE
      IERR = 0
C*** RECONSTRUCTED: THE NEXT TWO LINES ARE HIDDEN UNDER A PASTE-UP STRIP
C***      IN THE PUBLISHED LISTING (ONLY '...TO 300' IS VISIBLE).
      RETURN
   20 IF (IFAC .GE. 2) GO TO 300
      IF (IFAC .EQ. 1) GO TO 160
C
C* * * * * * * * * * * * * *   IFAC = 0   * * * * * * * * * * * * * * *
C
      MSUM(1)=0
      MSUM(2)=1
      DO 25 I=3,N
      II=I-1
   25 MSUM(I)=MSUM(II)+M(II)
      IFAC = 1
   30 DO 150 I=1,N
      IM1 = I-1
      MN=I-M(I)+1
      LO=MSUM(I)-I+M(I)
      DO 150 J=MN,I
      L=LO+J
      X = A(L)
      IF (I .GT. J) GO TO 110
      IF (IM1 .EQ. 0) GO TO 50
      IF(MN.GT.IM1) GO TO 50
      DO 40 K=MN,IM1
      L1=LO+K
      Y=A(L1)
      A(L1)=Y*P(K)
      X = X - Y*A(L1)
   40 CONTINUE
   50 IF (X .LE. 0) GO TO 999
      D(I)=X
      P(I) = 1.0 / X
  110 JM1 = J-1
      IF(JM1.EQ.0) GO TO 140
      MO=J-M(J)+1
      JO=MSUM(J)-J+M(J)
      IF(MN.GT.JM1) GO TO 140
      DO 120 K=MN,JM1
      IF(K.LT.MO) GO TO 120
      L1=LO+K
      L2=JO+K
      X = X - A(L1)*A(L2)
  120 CONTINUE
  140 A(L) = X
  150 CONTINUE
C
C* * * * * * * * * * * * * *   IFAC = 1   * * * * * * * * * * * * * * *
C
  160 DO 180 I=2,N
      IM1=I-1
      MN=I-M(I)+1
      LO=MSUM(I)-I+M(I)
C*** RECONSTRUCTED: NEXT THREE LINES ARE PARTLY OVERPRINTED IN THE
C***      PUBLISHED LISTING (FORWARD SUBSTITUTION, L*W = B).
      DO 180 J=1,NRHS
      X = B(I,J)
      DO 170 K=MN,IM1
      L=LO+K
      X = X - A(L)*B(K,J)
  170 CONTINUE
      B(I,J) = X
  180 CONTINUE
      Y = P(N)
      DO 190 J=1,NRHS
      B(N,J) = B(N,J)*Y
  190 CONTINUE
  200 I = NM1+1
      Y = P(NM1)
      DO 220 J=1,NRHS
      X = B(NM1,J)*Y
      DO 210 K=I,N
      LO=K-M(K)
      MO=LO+1
      IF(MO.GT.NM1) GO TO 210
      L=MSUM(K)+NM1-LO
      X = X - A(L)*B(K,J)
  210 CONTINUE
      B(NM1,J) = X
  220 CONTINUE
      NM1 = NM1-1
      IF (NM1 .GT. 0) GO TO 200
      IERR = 0
      RETURN
C
C* * * * * * * * * * * * * *   IFAC = 2 OR 3   * * * * * * * * * * * * *
C
  300 IF(NC.EQ.N) GO TO 312
      NN=N-1
      DO 305 I=1,N
  305 W(I)=Z(I)
      DO 310 J=NC,NN
      Z(J)=W(J)
      D(J)=D(J)+ALP*Z(J)**2
      BETA=ALP*Z(J)/D(J)
      ALP=ALP/(D(J)*P(J))
      P(J)=1.0/D(J)
C*** RECONSTRUCTED: THIS LINE IS HIDDEN UNDER A PASTE-UP STRIP IN THE
C***      PUBLISHED LISTING (ROW LOOP OF THE RANK-ONE UPDATE).
      DO 310 I=J+1,N
      LO=I-M(I)
      MO=LO+1
      IF(MO.GT.J) GO TO 310
      L=MSUM(I)+J-LO
      W(I)=W(I)-Z(J)*A(L)
      A(L)=A(L)+BETA*W(I)
  310 CONTINUE
      GO TO 313
  312 D(NC)=D(NC)+ALP*Z(NC)**2
      P(NC)=1.0/D(NC)
  313 DO 315 I=1,N
  315 Z(I)=0.0
      IF (IFAC. EQ. 3) GO TO 320
      IFAC=1
      GO TO 160
  320 IFAC = 1
      RETURN
  999 IERR=1
      RETURN
      END
