      SUBROUTINE PLOUT(NODE1,NODE2,NELE1,NELE2)
C
C     PRINTS OUT APPLIED STRESS, CRACK LENGTH, DISPLACEMENTS  AT
C     NODES NODE1 TO NODE2, AND STRESSES AND STRAINS FOR ELEMENTS
C     NELE1 TO NELE2
C
