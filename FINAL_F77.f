     14.0*1.0/AREA(NTRI))+AA(NUIU)
 1001 CONTINUE
      NUJU=MSUM(NU)-NU+MB(NU)+JU
      IF(JU.GT.NU) GO TO 1002
C*** CORRECTED: PUBLISHED LISTING READS (YR(J)-YR(2)); SHOULD BE YR(K)
      AA(NUJU) =((BETA1*(YR(K)-YR(I))*(YR(J)-YR(K))+BETA2*(XR(I)-XR(K))
     1*(XR(K)-XR(J)))*G/4.0*1.0/AREA(NTRI))+AA(NUJU)
 1002 CONTINUE
      NUKU=MSUM(NU)-NU+MB(NU)+KU
      IF(KU.GT.NU) GO TO 1003
C*** CORRECTED: PUBLISHED LISTING READS (YR(J)-YR(2)); SHOULD BE YR(K)
      AA(NUKU) =((BETA1*(YR(I)-YR(J))*(YR(J)-YR(K))+BETA2*(XR(J)-XR(I))
     1*(XR(K)-XR(J)))*G/4.0*1.0/AREA(NTRI))+AA(NUKU)
 1003 CONTINUE
      NVIU=MSUM(NV)-NV+MB(NV)+IU
      IF(IU.GT.NV) GO TO 1004
C*** CORRECTED: PUBLISHED LISTING READS (YR(J)-YR(2)); SHOULD BE YR(K)
      AA(NVIU) =((BETA3*(XR(K)-XR(J))*(YR(J)-YR(K))+BETA2*(YR(J)-YR(K))
     1*(XR(K)-XR(J)))*G/4.0*1.0/AREA(NTRI))+AA(NVIU)
 1004 CONTINUE
      NVJU=MSUM(NV)-NV+MB(NV)+JU
      IF(JU.GT.NV) GO TO 1005
      AA(NVJU) =((BETA3*(XR(I)-XR(K))*(YR(J)-YR(K))+BETA2*(YR(K)-YR(I))
     1*(XR(K)-XR(J)))*G/4.0*1.0/AREA(NTRI))+AA(NVJU)
 1005 CONTINUE
      NVKU=MSUM(NV)-NV+MB(NV)+KU
      IF(KU.GT.NV) GO TO 1006
      AA(NVKU) =((BETA3*(XR(J)-XR(I))*(YR(J)-YR(K))+BETA2*(YR(I)-YR(J))
     1*(XR(K)-XR(J)))*G/4.0*1.0/AREA(NTRI))+AA(NVKU)
 1006 CONTINUE
      NVIV=MSUM(NV)-NV+MB(NV)+IV
      IF(IV.GT.NV) GO TO 1007
      AA(NVIV) =((BETA1*((XR(K)-XR(J))**2)+BETA2*((YR(J)-YR(K))**2))
     1*G/4.0*1.0/AREA(NTRI))+AA(NVIV)
 1007 CONTINUE
      NVJV=MSUM(NV)-NV+MB(NV)+JV
      IF(JV.GT.NV) GO TO 1008
      AA(NVJV) =((BETA1*(XR(I)-XR(K))*(XR(K)-XR(J))+BETA2*(YR(K)-YR(I))
     1*(YR(J)-YR(K)))*G/4.0*1.0/AREA(NTRI))+AA(NVJV)
 1008 CONTINUE
      NVKV=MSUM(NV)-NV+MB(NV)+KV
      IF(KV.GT.NV) GO TO 1009
      AA(NVKV) =((BETA1*(XR(J)-XR(I))*(XR(K)-XR(J))+BETA2*(YR(I)-YR(J))
     1*(YR(J)-YR(K)))*G/4.0*1.0/AREA(NTRI))+AA(NVKV)
 1009 CONTINUE
      NUIV=MSUM(NU)-NU+MB(NU)+IV
      IF(IV.GT.NU) GO TO 1011
C*** CORRECTED: PUBLISHED LISTING READS (XR(K)-XR(1)); SHOULD BE XR(J)
      AA(NUIV) =((BETA3*(YR(J)-YR(K))*(XR(K)-XR(J))+BETA2*(XR(K)-XR(J))
     1*(YR(J)-YR(K)))*G/4.0*1.0/AREA(NTRI))+AA(NUIV)
 1011 CONTINUE
      NUJV=MSUM(NU)-NU+MB(NU)+JV
      IF(JV.GT.NU) GO TO 1012
      AA(NUJV) =((BETA3*(YR(K)-YR(I))*(XR(K)-XR(J))+BETA2*(XR(I)-XR(K))
     1*(YR(J)-YR(K)))*G/4.0*1.0/AREA(NTRI))+AA(NUJV)
 1012 CONTINUE
      NUKV=MSUM(NU)-NU+MB(NU)+KV
      IF(KV.GT.NU) GO TO 1013
C*** CORRECTED: PUBLISHED LISTING READS (XR(K)-XR(1)); SHOULD BE XR(J)
      AA(NUKV) =((BETA3*(YR(I)-YR(J))*(XR(K)-XR(J))+BETA2*(XR(J)-XR(I))
     1*(YR(J)-YR(K)))*G/4.0*1.0/AREA(NTRI))+AA(NUKV)
 1013 CONTINUE
      GO TO 403
  402 CONTINUE
C
C     PRINT OUT STIFFNESS MATRIX IF REQUIRED
C
      IF(LPRIT.EQ.0) GO TO 705
      DO 505 L=1,LDOF
  505 WRITE(6,507) L,AA(L)
  507 FORMAT(5X,I8,4X,E16.7)
  705 CONTINUE
C
C     LOADING (UNIFORM STRESS ACTING IN X- OR Y-DIRECTION ON BOUNDARY I)
C
      DO 408 N=1,2
      DO 408 K=1,NB
      IF(N.EQ.1.AND.NBX(K).NE.2) GO TO 408
      IF(N.EQ.2.AND.NBY(K).NE.2) GO TO 408
      SBK=SBX(K)
      IF(N.EQ.2) SBK=SBY(K)
      NBK=NOD(K)
      DO 409 I=1,NBK
      L=LSAME(K,I)
      NX=2*L-1
      IF(N.EQ.2) NX=NX+1
      IX=IIMAX(L)
      DO 410 M=1,IX
      MN=NSAME(L,M)
      DO 410 J=1,3
      MX=MSAME(MN,J)
      DO 410 II=1,NBK
      LX=LSAME(K,II)
      IF(MX.NE.LX) GO TO 410
      RX=SQRT((XR(L)-XR(MX))**2+(YR(L)-YR(MX))**2)
      BB(NX,1)=BB(NX,1)+SBK*RX/2.0
      R(NX)=BB(NX,1)
  410 CONTINUE
  409 CONTINUE
  408 CONTINUE
C
C     PRINT OUT APPLIED LOAD VECTOR IF REQUIRED
C
      IF(LPRIT.EQ.0) GO TO 706
      WRITE(6,500)
  500 FORMAT(7X,1HI,8X,7HBB(I,1))
      DO 412 I=1,LL
  412 WRITE(6,413) I,BB(I,1)
  413 FORMAT(5X,I5,E16.7)
  706 CONTINUE
C
C     FIXED BOUNDARY CONDITIONS ARE SATISFIED BY RIGID SPRINGS
C
      SK2=1.0E+07 * CE
      DO 404 K=1,NB
      IF(NBX(K).NE.1) GO TO 404
      NX=NOD(K)
      DO 405 I=1,NX
      L=LSAME(K,I)
      NU=2*L-1
      NUNU=MSUM(NU)+MB(NU)
      MPTAB(NU)=1
  405 AA(NUNU)=AA(NUNU)+SK2
  404 CONTINUE
      CRACK1=CRACK-0.001
      DO 406 K=1,NB
      IF(NBY(K).NE.1) GO TO 406
      NY=NOD(K)
      DO 407 I=1,NY
      L=LSAME(K,I)
      IF(K.EQ.NBC.AND.XR(L).LT.CRACK1) GO TO 407
      NV=2*L
      NVNV=MSUM(NV)+MB(NV)
      MPTAB(NV)=1
      AA(NVNV)=AA(NVNV)+SK2
  407 CONTINUE
  406 CONTINUE
C
C     MATRIX SOLUTION ROUTINE
C
      IFAC=0
      CALL SYMBAN(MAXA,LL,MB,MSUM,AA,1,BB,IFAC,T1,IERR,ALP,Z,T2,T3,NC)
      WRITE(6,415) IERR
  415 FORMAT(10X,' IERR = ',I2)
C
C     PRINT OUT UNIT LOAD DISPLACEMENTS AND STRESSES
C
      DO 414 N=1,LMAX
      NU=2*N-1
      NV=NU+1
      U(N)=BB(NU,1)
      V(N)=BB(NV,1)
  414 CONTINUE
      WRITE(6,425)
  425 FORMAT(//,10X,'UNIT LOAD DISPLACEMENTS AND STRESSES',//)
      WRITE(6,418)
  418 FORMAT(5X,4HNODE,7X,1HX,15X,1HY,15X,1HU,15X,1HV,/)
      DO 419 I=1,LMAX
      WRITE(6,420) I,XR(I),YR(I),U(I),V(I)
  420 FORMAT(5X,I5,4E16.7)
  419 CONTINUE
      WRITE(6,430)
      DO 421 NTRI=1,KMAX
      N1=MSAME(NTRI,1)
      N2=MSAME(NTRI,2)
      N3=MSAME(NTRI,3)
      ALP2=(U(N1)*(YR(N2)-YR(N3))+U(N2)*(YR(N3)-YR(N1))+
     1U(N3)*(YR(N1)-YR(N2)))/(2.0*AREA(NTRI))
      ALP5=(V(N1)*(YR(N2)-YR(N3))+V(N2)*(YR(N3)-YR(N1))+
     1V(N3)*(YR(N1)-YR(N2)))/(2.0*AREA(NTRI))
      ALP3=(U(N1)*(XR(N3)-XR(N2))+U(N2)*(XR(N1)-XR(N3))+
     1U(N3)*(XR(N2)-XR(N1)))/(2.0*AREA(NTRI))
      ALP6=(V(N1)*(XR(N3)-XR(N2))+V(N2)*(XR(N1)-XR(N3))+
     1V(N3)*(XR(N2)-XR(N1)))/(2.0*AREA(NTRI))
      STRX(NTRI)=ALP2
      STRY(NTRI)=ALP6
      STRXY(NTRI)=ALP3+ALP5
      SIGX(NTRI)=(CE/(1.0-CMU**2))*(ALP2+CMU*ALP6)
      SIGY(NTRI)=(CE/(1.0-CMU**2))*(ALP6+CMU*ALP2)
      TAU(NTRI)=(CE/(2.0*(1.0+CMU)))*(ALP3+ALP5)
  421 CONTINUE
      WRITE(6,422)
  422 FORMAT(6X,3HTRI,5X,4HSIGX,12X,4HSIGY,13X,3HTAU,13X,1HI,7X,1HJ,7X,
     1                                                         1HK,/)
      SYLD=0.0
      MAX=0
      DO 424 M=1,KMAX
      I=MSAME(M,1)
      J=MSAME(M,2)
      K=MSAME(M,3)
      SIGE(M)=SQRT(SIGX(M)**2+SIGY(M)**2-SIGX(M)*SIGY(M)+3*TAU(M)**2)
      IF(SIGE(M).GT.SYLD) MAX=M
      IF(SIGE(M).GT.SYLD) SYLD=SIGE(M)
      WRITE(6,423) M,SIGX(M),SIGY(M),TAU(M),I,J,K
  423 FORMAT(5X,I5,3E16.7,3X,I5,3X,I5,3X,I5)
  424 CONTINUE
      WRITE(6,430)
  430 FORMAT(//)
      WRITE(6,448) CE,CMU
  448 FORMAT(10X,'MODULUS OF ELASTICITY =',E10.3,'  KSI',10X,
     1'POISSON RATIO =',F6.2,//)
      IF(NEP.EQ.0) GO TO 999
      READ(5,2) SIGYS,AM
      WRITE(6,450) SIGYS,AM
  450 FORMAT(10X,'TENSILE YIELD STRESS = ',F6.2,' KSI',10X,
     1' STRAIN HARDENING COEFFICIENT = ',F6.2,//)
      SYLD=SIGYS/SYLD
      WRITE(6,440) SYLD,MAX
  440 FORMAT(10X,'APPLIED STRESS AT INITIAL YIELD IS ',F6.2,
     1' KSI AT ELEMENT',I5//)
      IF(MPS.EQ.1.AND.NEP.GT.0) PRINT 4
    4 FORMAT(10X,'PROGRAM CANNOT EXECUTE PLANE STRAIN PLASTICITY ')
      IF(MPS.EQ.1.AND.NEP.GT.0) GO TO 999
C
      CALL PLAS
C
  999 STOP
      END
      SUBROUTINE PLAS
C
C     PERFORMS AN INCREMENTAL PLASTICITY ANALYSIS FOR AN ELASTIC-
C     PERFECTLY PLASTIC MATERIAL
C
C*** F77: THE CDC 6000 SERIES USED 60-BIT SINGLE PRECISION (ABOUT 14
C***      DIGITS).  32-BIT REAL IS NOT ADEQUATE FOR THIS PROGRAM (THE
C***      RIGID-SPRING STIFFNESS SK2 = 1.0E7*CE IS ADDED TO AND LATER
C***      REMOVED FROM THE FACTORED MATRIX), SO DOUBLE PRECISION IS USED.
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
C*** DIMENSIONS ENLARGED (PUBLISHED: 400 ELEMENTS, 250 NODES, 500 DOF,
C*** 12000 STIFFNESS WORDS, 6 BOUNDARIES, 50 NODES PER BOUNDARY,
C*** 8 ELEMENTS PER NODE).  CHANGE THEM HERE, IDENTICALLY IN EVERY
C*** ROUTINE THAT CONTAINS /MAIN/.
C***   MAXEL  - ELEMENTS (AFTER SUBDIVISION)
C***   MAXNOD - NODES          MAXDOF - DEGREES OF FREEDOM (2*MAXNOD)
C***   MAXA   - STIFFNESS MATRIX STORAGE (VARIABLE-BANDWIDTH PROFILE)
C***   MAXBND - BOUNDARIES     MAXBN  - NODES ON ONE BOUNDARY
C***   MAXEPN - ELEMENTS CONNECTED TO ONE NODE
      PARAMETER (MAXEL=4000,MAXNOD=2500,MAXDOF=2*MAXNOD,MAXA=2000000,
     1           MAXBND=10,MAXBN=500,MAXEPN=12)
      COMMON / MAIN / AA(MAXA),BB(MAXDOF,1),MB(MAXDOF),MSUM(MAXDOF),
     1 T1(MAXDOF),T2(MAXDOF),T3(MAXDOF),Z(MAXDOF),X(MAXEL,3),Y(MAXEL,3),
     2 XR(MAXNOD),YR(MAXNOD),AREA(MAXEL),U(MAXNOD),V(MAXNOD),
     2 NOD(MAXBND),
     3 LSAME(MAXBND,MAXBN),NSAME(MAXNOD,MAXEPN),NBC,MSAME(MAXEL,3),
     4 IIMAX(MAXNOD),SIGE(MAXEL),SIGX(MAXEL),SIGY(MAXEL),TAU(MAXEL),
     5 STRX(MAXEL),STRY(MAXEL),STRXY(MAXEL),MPTAB(MAXDOF),R(MAXDOF),
     6 V2(MAXNOD),Q(MAXDOF),
     7 LMAX,KMAX,LPRIT,NEP,KNEW,KLU,SK2,CRACK,NODE,NELE,NDOF,PMAX,
     8 WIDTH,SNET,SYLD,SIGYS,AM,CE,CMU,UOLD(MAXNOD),VOLD(MAXNOD),
     9 MPLAS(MAXEL)
C*** F77: PUBLISHED  DATA HALT/4HHALT/,GROW/4HGROW/  (HOLLERITH IN REAL)
      CHARACTER*4 HALT,GROW,WORD
      DATA HALT/'HALT'/,GROW/'GROW'/
C
C     SIGYS = TENSILE YIELD STRESS
C     AM = STRAIN HARDENING COEFFICIENT
C          (SLOPE OF EFFECTIVE STRESS-STRAIN CURVE IN PLASTIC RANGE
C           DIVIDED BY THE MODULUS OF ELASTICITY)
C           MUST BE SET EQUAL TO 0 IN PRESENT PROGRAM
C     S = DESIRED NOMINAL STRESS
C     SNET = NOMINAL STRESS (=PT/WIDTH)
C     PT = TOTAL LOAD ACTING IN Y-DIRECTION
C     WIDTH = WIDTH OF PLATE ALONG X-AXIS
C     PCT = PERCENTAGE USED TO COMPUTE INCREMENTAL LOAD
C     MAXIT = MAXIMUM NUMBER OF ITERATIONS ALLOWED
C     ERIT = ERROR CHECK ON CONVERGENCE OF DISPLACEMENTS
C     G = RELAXATION PARAMETER (IMPROVES CONVERGENCE)
C        G = 1.0  NORMAL CONVERGENCE
C
C     INITIALIZATIONS
C
      NODE=LMAX
      NDOF=2*NODE
      NELE=KMAX
      SIGO=SIGYS
      PT=0.0
      DO 8 I=1,NDOF
C*** F77: PUBLISHED  Q(I)=Z(I)=0.0  (CDC MULTIPLE REPLACEMENT)
      Q(I)=0.0
      Z(I)=0.0
      R(I)=SYLD*R(I)
    8 CONTINUE
      DO 9 I=1,NODE
      NV=2*I
      PT=PT+R(NV)
      PYLD=PT
      UOLD(I)=U(I)*SYLD
    9 VOLD(I)=V(I)*SYLD
      DO 10 M=1,NELE
      MPLAS(M)=0
      SIGX(M)=SIGX(M)*SYLD
      SIGY(M)=SIGY(M)*SYLD
      TAU(M)=TAU(M)*SYLD
      STRX(M)=STRX(M)*SYLD
      STRY(M)=STRY(M)*SYLD
      STRXY(M)=STRXY(M)*SYLD
   10 CONTINUE
      READ(5,11) G
      READ(5,11) PCT,ERIT,MAXIT,NODE1,NODE2,NELE1,NELE2
   11 FORMAT(2E10.3,5I5)
      READ(5,12) S,WORD
   12 FORMAT(E10.3,1X,A4)
      PRINT 13, S,PCT,ERIT,MAXIT
   13 FORMAT(//10X,' S =',F8.2,' KSI',5X,' PCT =',E10.3,5X,'ERIT = ',
     1E10.3,5X,'MAXIT = ',I3//)
      DELP=PCT*PT
C
C     INCREMENT LOAD
C
      NPL=0
C*** F77: MP IS NOT INITIALISED IN THE PUBLISHED LISTING (CDC MEMORY WAS
C***      ZERO-FILLED AT LOAD TIME). EXPLICIT INITIALISATION ADDED.
      MP=0
   20 PMAX=PT
      PT=PT+DELP
      NPL=NPL+1
      KLU=0
      ICON=0
      DO 25 M=1,NELE
   25 MPLAS(M)=0
      DO 30 I=1,NODE
   30 V2(I)=VOLD(I)
C
C     HOLDING APPLIED LOAD CONSTANT -- ITERATE UNTIL DISPLACEMENTS CONVERGE
C
   45 DO 50 ITER=1,MAXIT
      DO 65 I=1,NDOF
      BB(I,1)=R(I)*PT/PYLD+Q(I)
      IF(LPRIT.EQ.0) GO TO 65
      PRINT 41, R(I),Q(I),BB(I,1)
   41 FORMAT(10X,3E10.3)
   65 CONTINUE
C
C     SOLVE FOR NEW DISPLACEMENTS
C
      IFAC=1
      CALL SYMBAN(MAXA,NDOF,MB,MSUM,AA,1,BB,IFAC,T1,IERR,ALP,Z,T2,T3,
     1                                                              NC)
C
      DO 70 N=1,NODE
      NU=2*N-1
      NV=NU+1
      U(N)=BB(NU,1)
      V(N)=BB(NV,1)
      U(N)=U(N)-UOLD(N)
      V(N)=V(N)-VOLD(N)
      IF(LPRIT.EQ.0) GO TO 69
      PRINT 71, ITER,U(N),V(N)
   71 FORMAT(10X,I5,2E10.3)
   69 CONTINUE
      UOLD(N)=BB(NU,1)
      VOLD(N)=BB(NV,1)
   70 CONTINUE
C
C     COMPUTE TOTAL STRAIN INCREMENTS FROM DISPLACEMENT INCREMENTS
C     COMPUTE ELASTIC STRESS INCREMENTS AND ADD TO CURRENT STRESSES
C     CHECK YIELD CONDITION FOR PLASTIC ELEMENTS
C
      DO 80 M=1,NELE
      N1=MSAME(M,1)
      N2=MSAME(M,2)
      N3=MSAME(M,3)
      ARD=0.5/AREA(M)
      B1=YR(N2)-YR(N3)
      C1=XR(N3)-XR(N2)
      B2=YR(N3)-YR(N1)
      C2=XR(N1)-XR(N3)
      B3=YR(N1)-YR(N2)
      C3=XR(N2)-XR(N1)
      ALP2=(U(N1)*B1+U(N2)*B2+U(N3)*B3)*ARD
      ALP5=(V(N1)*B1+V(N2)*B2+V(N3)*B3)*ARD
      ALP3=(U(N1)*C1+U(N2)*C2+U(N3)*C3)*ARD
      ALP6=(V(N1)*C1+V(N2)*C2+V(N3)*C3)*ARD
      STRX(M)=STRX(M)+ALP2
      STRY(M)=STRY(M)+ALP6
      STRXY(M)=STRXY(M)+ALP3+ALP5
      DSTRX=ALP2
      DSTRY=ALP6
      DSTRXY=ALP3+ALP5
      DSIGX=(CE/(1.0-CMU**2))*(ALP2+CMU*ALP6)
      DSIGY=(CE/(1.0-CMU**2))*(ALP6+CMU*ALP2)
      DTAU=(CE/(2.0*(1.0+CMU)))*(ALP3+ALP5)
      SX=SIGX(M)
      SY=SIGY(M)
      TXY=TAU(M)
      S1=SQRT(SX**2+SY**2-SX*SY+3.*TXY**2)
      SIGX(M)=SX+DSIGX
      SIGY(M)=SY+DSIGY
      TAU(M)=TXY+DTAU
      IF(ICON.EQ.1) GO TO 80
      S2=SQRT(SIGX(M)**2+SIGY(M)**2-SIGX(M)*SIGY(M)+3.*TAU(M)**2)
      IF(ABS(S2).LT.ABS(S1)) GO TO 80
      IF(ABS(S2).LE.SIGO) GO TO 80
      MPLAS(M)=M
      MP=1
C
C     COMPUTE THE PLASTIC LOAD VECTOR FOR ELEMENT M
C
      A=DSIGX**2+DSIGY**2-DSIGX*DSIGY+3.*DTAU**2
      B=SX*(2.*DSIGX-DSIGY)+SY*(2.*DSIGY-DSIGX)+6.*TXY*DTAU
      C=S1**2-SIGO**2
      AMIN=1.0E-10
      IF(A.LT.AMIN) GO TO 80
      DISCR=B**2-4.*A*C
      IF(DISCR.LT.0.0) GO TO 75
      GO TO 77
   75 PRINT 76, A,B,C
   76 FORMAT(10X,'NEG. DISCR',5X,'A =',E10.3,5X,'B =',E10.3,5X,
     1'C =',E10.3)
      PX=0.0
      GO TO 78
   77 DISCR=SQRT(DISCR)
      PONE=(-B+DISCR)/(2.*A)
      PTWO=(-B-DISCR)/(2.*A)
      PX=PONE
      IF(ABS(PONE).GT.ABS(PTWO)) PX=PTWO
      IF(LPRIT.EQ.0) GO TO 78
      PRINT 79, PONE,PTWO
   79 FORMAT(10X,'PONE =',E10.3,5X,'PTWO =',E10.3)
   78 CONTINUE
      SX=SX+PX*DSIGX
      SY=SY+PX*DSIGY
      TXY=TXY+PX*DTAU
      S1=SQRT(SX**2+SY**2-SX*SY+3.*TXY**2)
      DSTRX=(1.-PX)*DSTRX
      DSTRY=(1.-PX)*DSTRY
      DSTRXY=(1.-PX)*DSTRXY
C     CONVERGENCE IS IMPROVED BY USE OF THE RELAXATION PARAMETER G
      DSTRX=G*DSTRX
      DSTRY=G*DSTRY
      DSTRXY=G*DSTRXY
      FX=(SX-0.5*SY)/SIGO
      FY=(SY-0.5*SX)/SIGO
      FXY=3.*TXY/SIGO
      RO=FX**2+2.*CMU*FX*FY+FY**2+(1.-CMU)*0.5*FXY**2+(1.-CMU**2)*AM
      A11=FX**2+2.*CMU*FX*FY+CMU**2*FY**2
      A12=FX*FY+CMU*(FX**2+FY**2)
      A21=A12
      A13=(1.-CMU)*0.5*FXY*(FX+CMU*FY)
      A31=A13
      A22=FY**2+2.*CMU*FX*FY+CMU**2*FX**2
      A23=(1.-CMU)*0.5*FXY*(FY+CMU*FX)
      A32=A23
      A33=((1.-CMU)*0.5*FXY)**2
      RE=CE/(RO*(1.0-CMU**2))
      SIGXP=RE*(A11*DSTRX+A12*DSTRY+A13*DSTRXY)
      SIGYP=RE*(A21*DSTRX+A22*DSTRY+A23*DSTRXY)
      TAUP =RE*(A31*DSTRX+A32*DSTRY+A33*DSTRXY)
      SIGX(M)=SIGX(M)-SIGXP
      SIGY(M)=SIGY(M)-SIGYP
      TAU(M)=TAU(M)-TAUP
      SIGE(M)=SQRT(SIGX(M)**2+SIGY(M)**2-SIGX(M)*SIGY(M)+3.*TAU(M)**2)
      NU1=2*N1-1
      NV1=NU1+1
      NU2=2*N2-1
      NV2=NU2+1
      NU3=2*N3-1
      NV3=NU3+1
      AR=0.5
      Q(NU1)=Q(NU1)+AR*(B1*SIGXP+C1*TAUP)
      Q(NU2)=Q(NU2)+AR*(B2*SIGXP+C2*TAUP)
      Q(NU3)=Q(NU3)+AR*(B3*SIGXP+C3*TAUP)
      Q(NV1)=Q(NV1)+AR*(C1*SIGYP+B1*TAUP)
      Q(NV2)=Q(NV2)+AR*(C2*SIGYP+B2*TAUP)
      Q(NV3)=Q(NV3)+AR*(C3*SIGYP+B3*TAUP)
      IF(LPRIT.EQ.0) GO TO 80
      PRINT 81,M,S1,S2,SIGE(M),Q(NU1),Q(NV1),Q(NU2),Q(NV2),Q(NU3),Q(NV3)
   81 FORMAT(5X,I5,3X,3E10.3,3X,2E10.3,3X,2E10.3,3X,2E10.3)
   80 CONTINUE
C
C     CHECK CONVERGENCE OF DISPLACEMENTS
C
      IF(ICON.EQ.1) GO TO 90
      IF(MP.EQ.0) GO TO 90
      DO 51 I=1,NODE
      IF(ABS(U(I)).GT.ERIT*ABS(UOLD(I))) GO TO 49
      IF(ABS(V(I)).GT.ERIT*ABS(VOLD(I))) GO TO 49
   51 CONTINUE
      PRINT 52, ITER
   52 FORMAT(10X,'DISPLACEMENTS CONVERGED IN ',I4,' ITERATIONS')
      ICON=1
      GO TO 49
   53 PRINT 54, ITER
   54 FORMAT(10X,'NO CONVERGENCE IN ',I4,' ITERATIONS')
      CALL PLOUT(NODE1,NODE2,NELE1,NELE2)
      GO TO 999
   49 IF(ITER.EQ.MAXIT) GO TO 53
   50 CONTINUE
   90 CONTINUE
      MP=0
      ICON=0
      SNET=PT/ WIDTH
C
C     CHECK CRACK DISPLACEMENTS FOR CLOSURE OR OPENING
C
      CALL CONTACT
      IF(KNEW.EQ.1) GO TO 45
C
      IF(SNET.GE.S.AND.DELP.GT.0.0) CALL PLOUT(NODE1,NODE2,NELE1,NELE2)
      IF(SNET.LE.S.AND.DELP.LT.0.0) CALL PLOUT(NODE1,NODE2,NELE1,NELE2)
      IF(NPL.EQ.NEP) CALL PLOUT(NODE1,NODE2,NELE1,NELE2)
      IF(NPL.EQ.NEP) NPL=0
      IF(KLU.EQ.1) GO TO 102
      IF(SNET.LT.S.AND.DELP.GT.0.0) GO TO 20
      IF(SNET.GT.S.AND.DELP.LT.0.0) GO TO 20
C
C     CHECK FOR MAXIMUM LOAD AND GROW CRACK (CHANGE SPRING STIFFNESS)
C
      IF(WORD.EQ.GROW) CALL BREAK
      IF(KLU.EQ.1) GO TO 45
C
  102 DELP=-DELP
      READ(5,101) S,WORD
  101 FORMAT(E10.3,1X,A4)
      IF(WORD.EQ.HALT) GO TO 999
      GO TO 20
  999 RETURN
      END
      SUBROUTINE CONTACT
C
C     CHANGES SPRING STIFFNESS IF CRACK CLOSES OR OPENS
C
C*** F77: THE CDC 6000 SERIES USED 60-BIT SINGLE PRECISION (ABOUT 14
C***      DIGITS).  32-BIT REAL IS NOT ADEQUATE FOR THIS PROGRAM (THE
C***      RIGID-SPRING STIFFNESS SK2 = 1.0E7*CE IS ADDED TO AND LATER
C***      REMOVED FROM THE FACTORED MATRIX), SO DOUBLE PRECISION IS USED.
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
C*** DIMENSIONS ENLARGED (PUBLISHED: 400 ELEMENTS, 250 NODES, 500 DOF,
C*** 12000 STIFFNESS WORDS, 6 BOUNDARIES, 50 NODES PER BOUNDARY,
C*** 8 ELEMENTS PER NODE).  CHANGE THEM HERE, IDENTICALLY IN EVERY
C*** ROUTINE THAT CONTAINS /MAIN/.
C***   MAXEL  - ELEMENTS (AFTER SUBDIVISION)
C***   MAXNOD - NODES          MAXDOF - DEGREES OF FREEDOM (2*MAXNOD)
C***   MAXA   - STIFFNESS MATRIX STORAGE (VARIABLE-BANDWIDTH PROFILE)
C***   MAXBND - BOUNDARIES     MAXBN  - NODES ON ONE BOUNDARY
C***   MAXEPN - ELEMENTS CONNECTED TO ONE NODE
      PARAMETER (MAXEL=4000,MAXNOD=2500,MAXDOF=2*MAXNOD,MAXA=2000000,
     1           MAXBND=10,MAXBN=500,MAXEPN=12)
      COMMON / MAIN / AA(MAXA),BB(MAXDOF,1),MB(MAXDOF),MSUM(MAXDOF),
     1 T1(MAXDOF),T2(MAXDOF),T3(MAXDOF),Z(MAXDOF),X(MAXEL,3),Y(MAXEL,3),
     2 XR(MAXNOD),YR(MAXNOD),AREA(MAXEL),U(MAXNOD),V(MAXNOD),
     2 NOD(MAXBND),
     3 LSAME(MAXBND,MAXBN),NSAME(MAXNOD,MAXEPN),NBC,MSAME(MAXEL,3),
     4 IIMAX(MAXNOD),SIGE(MAXEL),SIGX(MAXEL),SIGY(MAXEL),TAU(MAXEL),
     5 STRX(MAXEL),STRY(MAXEL),STRXY(MAXEL),MPTAB(MAXDOF),R(MAXDOF),
     6 V2(MAXNOD),Q(MAXDOF),
     7 LMAX,KMAX,LPRIT,NEP,KNEW,KLU,SK2,CRACK,NODE,NELE,NDOF,PMAX,
     8 WIDTH,SNET,SYLD,SIGYS,AM,CE,CMU,UOLD(MAXNOD),VOLD(MAXNOD),
     9 MPLAS(MAXEL)
      NB=NBC
      NX=NOD(NB)
      DO 10 I=1,NX
      KNEW=0
      L=LSAME(NB,I)
      CX=XR(L)-CRACK
      IF(CX.LT.-0.001) GO TO 9
      GO TO 40
    9 NV=2*L
      MPTX=MPTAB(NV)
      IF(VOLD(L).LE.0.0) MPTAB(NV)=1
      IF(VOLD(L).GT.0.0) MPTAB(NV)=0
      IF(MPTX.NE.MPTAB(NV)) KNEW=1
      IF(KNEW.EQ.0) GO TO 40
      SMAX=PMAX/ WIDTH
      SN=SNET-((SNET-SMAX)/(VOLD(L)-V2(L)))*VOLD(L)
      Z(NV)=1.0
      NC=NV
      ALP=SK2
      IF(MPTAB(NV).EQ.0) ALP=-SK2
      IFAC=3
      CALL SYMBAN(MAXA,NDOF,MB,MSUM,AA,1,BB,IFAC,T1,IERR,ALP,Z,T2,T3,
     1                                                              NC)
      IF(MPTAB(NV).EQ.0) PRINT 20, L,SN
   20 FORMAT(10X,' NODE ',I5,' OPENED AT ',F8.2,' KSI',/)
      IF(MPTAB(NV).EQ.1) PRINT 30, L,SN
   30 FORMAT(10X,' NODE ',I5,' CLOSED AT ',F8.2,' KSI',/)
   40 CONTINUE
   10 CONTINUE
      RETURN
      END
      SUBROUTINE BREAK
C
