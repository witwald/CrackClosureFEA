C***      RIGID-SPRING STIFFNESS SK2 = 1.0E7*CE IS ADDED TO AND LATER
C***      REMOVED FROM THE FACTORED MATRIX), SO DOUBLE PRECISION IS USED.
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
C*** DIMENSIONS ENLARGED (PUBLISHED: 400 ELEMENTS, 250 NODES, 500 DOF,
C*** 12000 STIFFNESS WORDS, 6 BOUNDARIES, 50 NODES PER BOUNDARY,
C*** 8 ELEMENTS PER NODE).  CHANGE THEM HERE, IDENTICALLY IN EVERY
C*** ROUTINE THAT CONTAINS /MAIN/.
C***   MAXEL  - ELEMENTS (AFTER SUBDIVISION)
C***   MAXNOD - NODES          MAXDOF - DEGREES OF FREEDOM (2*MAXNOD)
C***   MAXA   - STIFFNESS MATRIX STORAGE (VARIABLE-BANDWIDTH PROFILE)
C***   MAXBND - BOUNDARIES     MAXBN  - NODES ON ONE BOUNDARY
C***   MAXEPN - ELEMENTS CONNECTED TO ONE NODE
