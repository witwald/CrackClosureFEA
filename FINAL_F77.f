C=======================================================================
C     PROGRAM FINAL  --  FORTRAN 77 VERSION
C
C     SOURCE: J. C. NEWMAN, JR., "FINITE-ELEMENT ANALYSIS OF FATIGUE
C     CRACK PROPAGATION -- INCLUDING THE EFFECTS OF CRACK CLOSURE",
C     PH.D. THESIS, VIRGINIA POLYTECHNIC INSTITUTE AND STATE UNIV.,
C     1974.  APPENDIX E, COMPUTER PROGRAM LISTING (THESIS PP. 102-121).
C
C     THE PUBLISHED CDC FORTRAN LISTING IS REPRODUCED STATEMENT FOR
C     STATEMENT, WITH THE SAME LABELS, COMMON BLOCK, CONTROL FLOW AND
C     INPUT CARD FORMATS.  EVERY DEPARTURE FROM THE PUBLISHED TEXT IS
C     MARKED IN-LINE WITH A COMMENT BEGINNING  C*** .  IN SUMMARY:
C
C     (A) DIALECT CHANGES NEEDED FOR STANDARD FORTRAN 77
C         - PROGRAM CARD FILE LIST REMOVED (UNITS 5/6 = STDIN/STDOUT)
C         - CDC *...* STRING DELIMITERS IN FORMATS CHANGED TO '...'
C         - CDC MULTIPLE REPLACEMENT  Q(I)=Z(I)=0.0  SPLIT IN TWO
C         - HOLLERITH DATA 4HHALT/4HGROW IN REAL VARIABLES REPLACED BY
C           CHARACTER*4 HALT, GROW, WORD
C         - SCALAR Q IN THE NODE-MERGING LOOP RENAMED QQ (Q IS AN
C           ARRAY IN /MAIN/)
C         - ELEMENT READ LOOP USES COUNTER ICARD BECAUSE THE READ
C           REDEFINES I (NOT PERMITTED FOR A DO VARIABLE IN F77)
C         - MP INITIALISED TO ZERO IN PLAS (CDC ZERO-FILLED MEMORY)
C         - IMPLICIT DOUBLE PRECISION IN EVERY PROGRAM UNIT, TO MATCH
C           THE ~14-DIGIT 60-BIT CDC SINGLE PRECISION
C     (B) EVIDENT MISPRINTS IN THE STIFFNESS ASSEMBLY CORRECTED
C         - YR(2) -> YR(K) IN AA(NUJU), AA(NUKU), AA(NVIU)
C         - XR(1) -> XR(J) IN AA(NUIV), AA(NUKV)
C     (C) SYMBAN LINES HIDDEN BY PASTE-UP STRIPS IN THE THESIS COPY
C         RECONSTRUCTED (4 + 3 LINES, MARKED  RECONSTRUCTED ).
C
C     (D) ARRAY DIMENSIONS ENLARGED TO 4000 ELEMENTS / 2500 NODES VIA
C         PARAMETER STATEMENTS, WITH DIMENSION CHECKS (SUBROUTINE
C         DIMERR) AND WIDER INTEGER FIELDS IN SOME OUTPUT FORMATS.
C
C     NOTE: THE PUBLISHED OFF-DIAGONAL U-V COUPLING TERMS AA(NVJU),
C     AA(NVKU), AA(NUJV), AA(NUKV) HAVE BETA2 AND BETA3 INTERCHANGED
C     RELATIVE TO THE CST STIFFNESS.  THIS IS EXACT ONLY WHEN
C     BETA2 = BETA3, I.E. CMU = 1/3 IN PLANE STRESS.  THE PUBLISHED
C     FORM IS RETAINED HERE.  USE CMU = 0.3333 TO REPRODUCE CORRECT
C     RESULTS, OR INTERCHANGE BETA2/BETA3 IN THOSE FOUR STATEMENTS.
C
C=======================================================================
      PROGRAM FINAL
C*** F77: CDC PROGRAM CARD WAS
C***      PROGRAM FINAL (INPUT,OUTPUT,TAPE5=INPUT,TAPE6=OUTPUT)
C***      UNITS 5 AND 6 ARE THE PRECONNECTED INPUT AND OUTPUT UNITS.
C*** F77: THE CDC 6000 SERIES USED 60-BIT SINGLE PRECISION (ABOUT 14
C***      DIGITS).  32-BIT REAL IS NOT ADEQUATE FOR THIS PROGRAM (THE
C***      RIGID-SPRING STIFFNESS SK2 = 1.0E7*CE IS ADDED TO AND LATER
C***      REMOVED FROM THE FACTORED MATRIX), SO DOUBLE PRECISION IS USED.
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
C*** DIMENSIONS ENLARGED (PUBLISHED: 400 ELEMENTS, 250 NODES, 500 DOF,
C*** 12000 STIFFNESS WORDS, 6 BOUNDARIES, 50 NODES PER BOUNDARY,
C*** 8 ELEMENTS PER NODE).  CHANGE THEM HERE, IDENTICALLY IN EVERY
C*** ROUTINE THAT CONTAINS /MAIN/.
C***   MAXEL  - ELEMENTS (AFTER SUBDIVISION)
C***   MAXNOD - NODES          MAXDOF - DEGREES OF FREEDOM (2*MAXNOD)
C***   MAXA   - STIFFNESS MATRIX STORAGE (VARIABLE-BANDWIDTH PROFILE)
C***   MAXBND - BOUNDARIES     MAXBN  - NODES ON ONE BOUNDARY
C***   MAXEPN - ELEMENTS CONNECTED TO ONE NODE
      PARAMETER (MAXEL=4000,MAXNOD=2500,MAXDOF=2*MAXNOD,MAXA=2000000,
     1           MAXBND=10,MAXBN=500,MAXEPN=12)
      COMMON / MAIN / AA(MAXA),BB(MAXDOF,1),MB(MAXDOF),MSUM(MAXDOF),
     1 T1(MAXDOF),T2(MAXDOF),T3(MAXDOF),Z(MAXDOF),X(MAXEL,3),Y(MAXEL,3),
     2 XR(MAXNOD),YR(MAXNOD),AREA(MAXEL),U(MAXNOD),V(MAXNOD),
     2 NOD(MAXBND),
     3 LSAME(MAXBND,MAXBN),NSAME(MAXNOD,MAXEPN),NBC,MSAME(MAXEL,3),
     4 IIMAX(MAXNOD),SIGE(MAXEL),SIGX(MAXEL),SIGY(MAXEL),TAU(MAXEL),
     5 STRX(MAXEL),STRY(MAXEL),STRXY(MAXEL),MPTAB(MAXDOF),R(MAXDOF),
     6 V2(MAXNOD),Q(MAXDOF),
     7 LMAX,KMAX,LPRIT,NEP,KNEW,KLU,SK2,CRACK,NODE,NELE,NDOF,PMAX,
     8 WIDTH,SNET,SYLD,SIGYS,AM,CE,CMU,UOLD(MAXNOD),VOLD(MAXNOD),
     9 MPLAS(MAXEL)
      DIMENSION B(MAXBND),C(MAXBND),D(MAXBND),E(MAXBND),XMAX(MAXBND),
     1 XMIN(MAXBND),YMAX(MAXBND),YMIN(MAXBND)
      DIMENSION NBX(MAXBND),NBY(MAXBND),SBX(MAXBND),SBY(MAXBND),
     1 XINT(MAXEL,3),YINT(MAXEL,3)
C * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * *
C
C     CONFIGURATION AND LOADING MUST BE SYMMETRIC ABOUT X-AXIS
C     MAXIMUM NUMBER OF ELEMENTS  400
C     MAXIMUM NUMBER OF NODES  250
C     MAXIMUM NUMBER OF BOUNDARIES IS 6
C     MINIMUM ELEMENT SIZE IS 0.001 UNITS
C     CRACK = INITIAL CRACK LENGTH (MUST LIE ON X-AXIS AND BE MEASURED FROM X=0)
C     WIDTH = WIDTH OF PLATE ALONG X-AXIS
C     THICKNESS - PLATE HAS UNIT THICKNESS
C     CE = MODULUS OF ELASTICITY
C     CMU = POISSON RATIO
C     MPS = 1  PLANE STRAIN , = 0  PLANE STRESS
C     IIMAX(N) = NUMBER OF ELEMENTS CONNECTED TO NODE N
C     NSAME(N,I) = ELEMENT NUMBER CONNECTED TO NODE N (I=1,IIMAX(N))
C     MSAME(M,I) = NODE NUMBERS FOR ELEMENT M  (I=1,3)
C     LMAX = TOTAL NUMBER OF NODES
C     IMAX = TOTAL NUMBER OF INITIAL ELEMENTS
C     NOD(I) = NUMBER OF NODES ON BOUNDARY I
C     LSAME(I,J) = NODE NUMBERS ON BOUNDARY I (J=1,NOD(I))
C     AREA(I) = AREA OF ELEMENT I
C     XR(N),YR(N) = COORDINATES FOR NODE N
C     X(I,J),Y(I,J) =NODAL COORDINATES FOR ELEMENT I (J=1,3)
C     LPRIT = 0   NO INTERNAL PRINTOUT, = 1  INTERNAL PRINTOUT
C     KMAX = TOTAL NUMBER OF ELEMENTS AFTER SUBDIVISIONS
C     NDIV = NUMBER OF SUBDIVISIONS OF THE ELEMENT MESH
C     NB = TOTAL NUMBER OF BOUNDARIES (MUST BE DESCRIBED IN ANALYTICAL FORM
C          EITHER STRAIGHT OR CIRCULAR BOUNDARIES)
C     XMAX(I),XMIN(I),YMAX(I),YMIN(I) = MAX. AND MIN. VALUE OF X AND Y
C                                       COORDINATES FOR BOUNDARY I
C     B(I),C(I),D(I),E(I)  ARE THE COEFFICIENTS OF THE ANALYTICAL
C                          EQUATION FOR BOUNDARY I
C        STRAIGHT BOUNDARY -  Y=B*X+C  WITH D=0 AND E=0
C        FOR STRAIGHT BOUNDARY PARALLEL TO Y-AXIS USE X=C WITH D=0 AND E=1
C        CIRCULAR BOUNDARY - (X-B)**2+(Y-C)**2=D**2   WITH E=0
C     NBC = BOUNDARY NUMBER CONTAINING CRACK
C     BOUNDARY CONDITIONS FOR BOUNDARY I ARE INPUT IN NBX(I) AND NBY(I)
C           NBX(I) OR NBY(I) = 0   FREE
C                            = 1   FIXED
C                            = 2   LOADED
C     LOADED BOUNDARIES HAVE UNIFORM STRESS
C        SBX(I) OR SBY(I) = UNIT APPLIED STRESS ON BOUNDARY I
C                           ACTING IN X- OR Y-DIRECTION
C     TOTAL LOAD ACTING IN Y-DIRECTION (NORMAL TO CRACK PLANE) IS
C     CONSIDERED THE PRIMARY LOADING AND MUST NOT BE ZERO.
C     NBX(I) = BOUNDARY CONDITION IN X-DIRECTION FOR BOUNDARY I
C     NBY(I) = BOUNDARY CONDITION IN Y-DIRECTION FOR BOUNDARY I
C     FOR BOUNDARY ON X-AXIS CONTAINING THE CRACK SET NBX(I)=0 AND NBY(I)=1
C         (PROGRAM WILL FREE NODES ALONG SPECIFIED CRACK LENGTH)
C     NEP = 0  ELASTIC ANALYSIS,  NEP GREATER THAN 0 INDICATES PLASTIC
C              ANALYSIS WITH PRINT OUT AT NEP INCREMENTS
C     NODAL COORDINATES X(I,J) AND Y(I,J) OF ELEMENT I ARE INPUT IN COUNTER
C     CLOCKWISE DIRECTION STARTING WITH ANY NODE (J=1,2,3) FOR THAT ELEMENT.
C
C     INPUT DATA
C
      READ(5,1) LPRIT,IMAX,NDIV,NB,NBC,NEP
    1 FORMAT(6I5)
C*** ADDED: DIMENSION CHECK (NOT IN PUBLISHED LISTING)
      IF(NB.GT.MAXBND) CALL DIMERR('BOUNDARIES (MAXBND)',NB,MAXBND)
      KCHK=IMAX*4**NDIV
      IF(KCHK.GT.MAXEL) CALL DIMERR('ELEMENTS (MAXEL)',KCHK,MAXEL)
      READ(5,2) CRACK, WIDTH
    2 FORMAT(4F10.4)
      DO 3 I=1,NB
      READ(5,2) B(I),C(I),D(I),E(I)
      READ(5,2) XMAX(I),XMIN(I),YMAX(I),YMIN(I)
      READ(5,1) NBX(I),NBY(I)
    3 READ(5,2) SBX(I),SBY(I)
      READ(5,2) CE,CMU
      READ(5,1) MPS
C*** F77: PUBLISHED  DO 7 I=1,IMAX  -- THE READ BELOW REDEFINES I, WHICH
C***      F77 FORBIDS FOR A DO VARIABLE, SO A SEPARATE COUNTER IS USED.
      DO 7 ICARD=1,IMAX
      READ(5,13) I,X(I,1),X(I,2),X(I,3),Y(I,1),Y(I,2),Y(I,3)
      IF(LPRIT.EQ.0) GO TO 7
      PRINT 13,I,X(I,1),X(I,2),X(I,3),Y(I,1),Y(I,2),Y(I,3)
   13 FORMAT(I5,6F10.4)
    7 CONTINUE
C
C     SUBDIVISION
C
C     SUBDIVIDES MESH USING THE INITIAL ELEMENT NUMBERING SCHEME IN RENUMBERING
C     ELEMENTS IN ORDER TO MAINTAIN REASONABLE BANDWIDTHS IN STIFFNESS MATRIX
C     (THE INITIAL ELEMENT NUMBERING SCHEME SHOULD BE NUMBERED TO HAVE
C     MINIMUM BANDWIDTHS.)
C
      DO 42 M=1,NB
      XMAX(M)=XMAX(M)+0.0001
      XMIN(M)=XMIN(M)-0.0001
      YMAX(M)=YMAX(M)+0.0001
      YMIN(M)=YMIN(M)-0.0001
   42 CONTINUE
      ND=-1
    9 ND=ND+1
      IF(LPRIT.EQ.0) GO TO 700
      WRITE(6,202)
  202 FORMAT(3X,8HTRIANGLE,2X,4HNODE,8X,1HX,15X,1HY)
  700 CONTINUE
      I=0
      KMAX=IMAX*(4**ND)
      IF(ND.EQ.0) GO TO 41
      K=IMAX*(4**(ND-1))
      KKK=K
   10 I=I+1
      J=0
   11 J=J+1
      K=K+1
      II=I
      JJ=J+1
      KK=K+1
      IF(J.EQ.3) II=K-2
      IF(J.EQ.3) JJ=J-2
      IF(J.EQ.3) KK=K-2
      X(K,J)=X(I,J)
      X(I,J)=0.5*(X(I,J)+X(II,JJ))
      X(K,JJ)=X(I,J)
      X(KK,J)=X(I,J)
      Y(K,J)=Y(I,J)
      Y(I,J)=0.5*(Y(I,J)+Y(II,JJ))
      Y(K,JJ)=Y(I,J)
      Y(KK,J)=Y(I,J)
      M=0
   12 M=M+1
      IF(M.GT.NB) GO TO 8
      IF(D(M).LT.0.0001) GO TO 12
      RES=SQRT(((X(K,J)-B(M))**2+(Y(K,J)-C(M))**2-(D(M))**2)**2)
      IF(RES.GT.0.0001) GO TO 12
      RES1=SQRT(((X(II,JJ)-B(M))**2+(Y(II,JJ)-C(M))**2-(D(M))**2)**2)
      IF(RES1.GT.0.0001) GO TO 12
      IF(X(K,J).LT.XMIN(M)) GO TO 12
      IF(X(K,J).GT.XMAX(M)) GO TO 12
      IF(Y(K,J).LT.YMIN(M)) GO TO 12
      IF(Y(K,J).GT.YMAX(M)) GO TO 12
      IF(X(II,JJ).LT.XMIN(M)) GO TO 12
      IF(X(II,JJ).GT.XMAX(M)) GO TO 12
      IF(Y(II,JJ).LT.YMIN(M)) GO TO 12
      IF(Y(II,JJ).GT.YMAX(M)) GO TO 12
      RS=SQRT((X(I,J)-B(M))**2+(Y(I,J)-C(M))**2)
      X(I,J)=B(M)+((X(I,J)-B(M))*D(M)/RS)
      Y(I,J)=C(M)+((Y(I,J)-C(M))*D(M)/RS)
      X(K,JJ)=X(I,J)
      X(KK,J)=X(I,J)
      Y(K,JJ)=Y(I,J)
      Y(KK,J)=Y(I,J)
      GO TO 12
    8 CONTINUE
      IF(J.EQ.3) GO TO 40
      GO TO 11
   40 IF(I.EQ.KKK) GO TO 45
      GO TO 10
C
C     RENUMBER NODES AND CALCULATION OF AREAS
C
   45 IX=IMAX*(4**(ND-1))
      M1=IX
      DO 46 M=1,IX
      MM=4*M-3
      DO 47 I=1,3
      XINT(MM,I)=X(M,I)
   47 YINT(MM,I)=Y(M,I)
      DO 48 K=1,3
      MM1=MM+K
      M1=M1+1
      DO 48 I=1,3
      XINT(MM1,I)=X(M1,I)
   48 YINT(MM1,I)=Y(M1,I)
   46 CONTINUE
      DO 49 M=1,KMAX
      DO 49 I=1,3
      X(M,I)=XINT(M,I)
   49 Y(M,I)=YINT(M,I)
   41 CONTINUE
      IF(LPRIT.EQ.0) GO TO 701
      DO 44 I=1,KMAX
      DO 44 J=1,3
      WRITE(6,203) I,J,X(I,J),Y(I,J)
  203 FORMAT(5X,I5,4X,I3,2E16.7)
   44 CONTINUE
  701 CONTINUE
      I=0
      L=0
   14 I=I+1
      IF(I.GT.KMAX) GO TO 30
      J=0
   15 L=L+1
C*** ADDED: DIMENSION CHECK (NOT IN PUBLISHED LISTING)
      IF(L.GT.MAXNOD) CALL DIMERR('NODES (MAXNOD)',L,MAXNOD)
   16 J=J+1
      XR(L)=X(I,J)
      YR(L)=Y(I,J)
      IF(I.EQ.1) GO TO 19
      LL=L-1
      DO 17 K=1,LL
C*** F77: PUBLISHED USES SCALAR Q HERE, BUT Q IS AN ARRAY IN /MAIN/.
C***      RENAMED QQ (LOCAL SCRATCH VALUE ONLY).
      QQ=ABS(XR(L)-XR(K))
      IF(QQ.LT.0.0001) GO TO 18
      GO TO 17
   18 QQ=ABS(YR(L)-YR(K))
      IF(QQ.LT.0.0001) GO TO 20
      GO TO 17
   17 CONTINUE
      GO TO 19
   20 L=L-1
   19 IF(J.EQ.3) GO TO 21
      GO TO 22
   21 S1=SQRT((X(I,J-2)-X(I,J-1))**2+(Y(I,J-2)-Y(I,J-1))**2)
      S2=SQRT((X(I,J-1)-X(I,J))**2+(Y(I,J-1)-Y(I,J))**2)
      S3=SQRT((X(I,J)-X(I,J-2))**2+(Y(I,J)-Y(I,J-2))**2)
      S=0.5*(S1+S2+S3)
      AREA(I)=SQRT(S*(S-S1)*(S-S2)*(S-S3))
   22 IF(J.EQ.3) GO TO 14
      GO TO 15
   30 CONTINUE
      LMAX=L
      IF(LPRIT.EQ.0) GO TO 702
      WRITE(6,204)
  204 FORMAT(3X,4HNODE,8X,1HX,15X,1HY)
      DO 100 N=1,LMAX
      WRITE(6,205) N,XR(N),YR(N)
  205 FORMAT(3X,I5,2E16.7)
  100 CONTINUE
      WRITE(6,206)
  206 FORMAT(3X,8HTRIANGLE,4X,4HAREA)
      DO 101 I=1,KMAX
      WRITE(6,207) I,AREA(I)
  207 FORMAT(5X,I5,E16.7)
  101 CONTINUE
C
C     BOUNDARY-NODE IDENTIFICATION
C
  702 CONTINUE
      N=0
      LMAX=L
   31 N=N+1
      IF(N.GT.NB) GO TO 35
      NOD(N)=0
      L=0
   32 L=L+1
      IF(D(N).LT.0.0001) GO TO 34
      RES1=SQRT(((XR(L)-B(N))**2+(YR(L)-C(N))**2-(D(N))**2)**2)
      IF(RES1.LT.0.0001) GO TO 38
      GO TO 39
   34 IF(E(N).GT.0.0001) GO TO 36
      RES=SQRT((YR(L)-B(N)*XR(L)-C(N))**2)
      GO TO 37
   36 RES=SQRT((XR(L)-B(N)*YR(L)-C(N))**2)
   37 IF(RES.LT.0.0001) GO TO 38
      GO TO 39
   38 IF(XR(L).LT.XMIN(N)) GO TO 39
      IF(XR(L).GT.XMAX(N)) GO TO 39
      IF(YR(L).LT.YMIN(N)) GO TO 39
      IF(YR(L).GT.YMAX(N)) GO TO 39
      NOD(N)=NOD(N)+1
C*** ADDED: DIMENSION CHECK (NOT IN PUBLISHED LISTING)
      IF(NOD(N).GT.MAXBN) CALL DIMERR('NODES ON A BOUNDARY (MAXBN)',
     1 NOD(N),MAXBN)
      I=NOD(N)
      LSAME(N,I)=L
      IF(LPRIT.EQ.0) GO TO 703
      WRITE(6,201) N,I,LSAME(N,I)
  201 FORMAT(5X,I3,4X,I5,4X,I5)
  703 CONTINUE
   39 IF(L.EQ.LMAX) GO TO 31
      GO TO 32
   35 IF(ND.LT.NDIV) GO TO 9
C
C     ELEMENT-NODE IDENTIFICATION
C
      DO 300 NODE=1,LMAX
      I=0
      DO 301 NTRI=1,KMAX
      J=0
  302 J=J+1
      CX=ABS(XR(NODE)-X(NTRI,J))
      CY=ABS(YR(NODE)-Y(NTRI,J))
      IF(CX.LT.0.001) GO TO 303
      IF(J.EQ.3) GO TO 301
      GO TO 302
  303 IF(CY.LT.0.001) GO TO 304
      IF(J.EQ.3) GO TO 301
      GO TO 302
  304 I=I+1
C*** ADDED: DIMENSION CHECK (NOT IN PUBLISHED LISTING)
      IF(I.GT.MAXEPN) CALL DIMERR('ELEMENTS AT A NODE (MAXEPN)',I,
     1 MAXEPN)
      NSAME(NODE,I)=NTRI
      IIMAX(NODE)=I
      MSAME(NTRI,J)=NODE
  301 CONTINUE
  300 CONTINUE
      IF(LPRIT.EQ.0) GO TO 704
      WRITE(6,308)
  308 FORMAT(5X,4HNODE,5X,1HI,3X,5HNSAME)
      DO 305 NODE=1,LMAX
      II=IIMAX(NODE)
      DO 306 I=1,II
      WRITE(6,307) NODE,I,NSAME(NODE,I)
  307 FORMAT(5X,I5,4X,I3,4X,I5)
  306 CONTINUE
  305 CONTINUE
      WRITE(6,309)
  309 FORMAT(5X,4HNTRI,5X,1HJ,3X,5HMSAME)
      DO 310 NTRI=1,KMAX
      DO 311 J=1,3
      WRITE(6,312) NTRI,J,MSAME(NTRI,J)
  312 FORMAT(5X,I5,4X,I3,4X,I5)
  311 CONTINUE
  310 CONTINUE
  704 CONTINUE
C
C     MATERIAL CONSTANTS
C
      IF(MPS.EQ.0) GO TO 333
C
C     MINIMIZATION OF POTENTIAL ENERGY - PLANE STRAIN
C
      G=CE/(2.0*(1.0+CMU)*(1.0-2.0*CMU))
      BETA1=2.0*(1.0-CMU)
      BETA2=1.0-2.0*CMU
      BETA3=2.0*CMU
      GO TO 334
C
C     MINIMIZATION OF POTENTIAL ENERGY - PLANE STRESS
C
  333 CONTINUE
      G=CE/(1.-CMU**2)
      BETA1=1.
C*** CORRECTED: EQUATIONS FOR BETA2 AND BETA3 HAVE BEEN
C*** IN ORDER TO ENSURE FORMULATION IS CORRECT FOR VALUES
C*** OF CMU .NE. 1/3.
      BETA2=CMU
      BETA3=(1.-CMU)/2.
  334 CONTINUE
C
C     DETERMINE BAND-WIDTHS FOR STIFFNESS MATRIX
C
      DO 350 NODE=1,LMAX
      MAXDIF=0
      IM=IIMAX(NODE)
      DO 351 M=1,IM
      NTRI=NSAME(NODE,M)
      DO 351 L=1,3
      NUM=MSAME(NTRI,L)
      NDIFF=2*IABS(NUM-NODE)
      IF(NDIFF.GT.MAXDIF) MAXDIF=NDIFF
  351 CONTINUE
      NU=2*NODE-1
      NV=NU+1
      MB(NU)=MAXDIF+1
      IF(MB(NU).GT.NU) MB(NU)=NU
      MB(NV)=MB(NU)+1
      IF(LPRIT.EQ.0) GO TO 350
      WRITE(6,506) NODE,NU,MB(NU),NV,MB(NV)
  506 FORMAT(10X,5I5)
  350 CONTINUE
      MSUM(1)=0
      MSUM(2)=1
      LO=2*LMAX
      DO 352 I=3,LO
      II=I-1
  352 MSUM(I)=MSUM(II)+MB(II)
      LDOF=MSUM(LO)+MB(LO)
C*** ADDED: DIMENSION CHECK (NOT IN PUBLISHED LISTING)
      IF(LDOF.GT.MAXA) CALL DIMERR('STIFFNESS STORAGE (MAXA)',LDOF,MAXA)
      WRITE(6,504) LDOF
  504 FORMAT(10X,'STORAGE REQUIREMENT FOR STIFFNESS MATRIX = ',I8)
C
C     ASSEMBLE STIFFNESS MATRIX
C
      LL=2*LMAX
      DO 400 I=1,LL
      MPTAB(I)=0
      R(I)=0.0
      BB(I,1)=0.0
  400 CONTINUE
      DO 401 L=1,LDOF
      AA(L)=0.0
  401 CONTINUE
      DO 402 NODE=1,LMAX
      IM=IIMAX(NODE)
      M=0
  403 M=M+1
      IF(M.GT.IM) GO TO 402
      NTRI=NSAME(NODE,M)
      L=0
  602 L=L+1
      CX=ABS(XR(NODE)-X(NTRI,L))
      CY=ABS(YR(NODE)-Y(NTRI,L))
      IF(CX.LT.0.001) GO TO 603
      IF(L.EQ.3) GO TO 601
      GO TO 602
  603 IF(CY.LT.0.001) GO TO 604
      GO TO 602
  604 IF(L.EQ.1) I=MSAME(NTRI,1)
      IF(L.EQ.1) J=MSAME(NTRI,2)
      IF(L.EQ.1) K=MSAME(NTRI,3)
      IF(L.EQ.2) I=MSAME(NTRI,2)
      IF(L.EQ.2) J=MSAME(NTRI,3)
      IF(L.EQ.2) K=MSAME(NTRI,1)
      IF(L.EQ.3) I=MSAME(NTRI,3)
      IF(L.EQ.3) J=MSAME(NTRI,1)
      IF(L.EQ.3) K=MSAME(NTRI,2)
  601 CONTINUE
      N=NODE
      IF(LPRIT.EQ.0) GO TO 707
      WRITE(6,800) N,IM,M,NTRI,L,I,J,K
  800 FORMAT(8(3X,I5))
  707 CONTINUE
      NU=2*N-1
      NV=NU+1
      IU=2*I-1
